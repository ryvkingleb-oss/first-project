function words(text) {
  return String(text || "")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/[*_#>`]/g, " ")
    .split(/\s+/)
    .filter(Boolean).length;
}

function pageWords(p) {
  const bits = [p.h1, p.lead, p.title, p.description];
  for (const b of p.blocks || []) {
    bits.push(b.heading, ...(b.paragraphs || []), ...(b.items || []));
    for (const f of b.faq || []) bits.push(f.q, f.a);
  }
  for (const f of p.faq || []) bits.push(f.q, f.a);
  return words(bits.filter(Boolean).join(" "));
}

function crumbs(...items) {
  return items.map((x) => (typeof x === "string" ? { name: x } : x));
}

function faqBlock(items) {
  return {
    heading: "Частые вопросы",
    faq: items,
    paragraphs: items.map((f) => `**${f.q}** ${f.a}`),
  };
}

