function articleFromMeta(meta) {
  const blocks = meta.sections.map(([heading, ...paragraphs]) => ({ heading, paragraphs }));
  blocks.push({
    heading: "Связанные материалы",
    items: [
      "[Миграционный учёт](/migracionnyj-uchet)",
      "[Регистрация иностранного гражданина](/registraciya-inostrannogo-grazhdanina)",
      "[Все статьи](/statyi)",
      `[${meta.cta.label}](${meta.cta.to})`,
    ],
  });
  blocks.push(faqBlock(meta.faq));
  blocks.push(disclaimer());
  // Expand with practical paragraphs until word target
  const page = {
    path: meta.path,
    type: "article",
    title: meta.title,
    description: meta.description,
    kicker: "Статья",
    h1: meta.h1,
    lead: meta.sections[0][1],
    breadcrumbs: crumbs(
      { name: "Главная", path: "/" },
      { name: "Статьи", path: "/statyi" },
      meta.crumb,
    ),
    blocks,
    faq: meta.faq,
    cta: meta.cta,
    priority: "0.75",
    changefreq: "monthly",
  };
  let guard = 0;
  while (pageWords(page) < 900 && guard < 8) {
    page.blocks.splice(-2, 0, {
      heading: guard === 0 ? "Практика без обещаний" : `Уточнения к теме (${guard + 1})`,
      paragraphs: [
        `Тема «${meta.h1}» связана с официальными бланками МВД. Сервис documentmigrant.ru помогает заполнить клетки и скачать файл для печати после тестовой оплаты без списания денег. В ведомство, на Госуслуги и в МФЦ заявление из кабинета не отправляется.`,
        `Перед подачей сверьте дату бланка на странице документа, актуальный перечень приложений и режим работы выбранного канала. Если ваша ситуация нестандартная — квота, особое основание, смена паспорта в день подачи — уточните требования в подразделении, а не только в справочной статье.`,
        `Схема раздела: хаб объясняет процедуру целиком, статья отвечает на один вопрос, страница документа даёт действие. Не смешивайте патент на работу с патентом ИП, уведомление о прибытии с заявлением на РВП и подтверждение проживания с первичным статусом.`,
        `Если вы пришли из поиска, откройте сначала подходящий хаб ([миграционный учёт](/migracionnyj-uchet) или [регистрация иностранного гражданина](/registraciya-inostrannogo-grazhdanina)), затем эту статью, затем CTA на документ. Так меньше риск заполнить не тот бланк.`,
      ],
    });
    guard += 1;
  }
  return page;
}

