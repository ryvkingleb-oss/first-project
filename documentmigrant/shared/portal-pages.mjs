export function portalPageByPath(pathname) {
  const raw = String(pathname || "/").split("?")[0].split("#")[0] || "/";
  const path = raw.length > 1 && raw.endsWith("/") ? raw.slice(0, -1) : raw;
  return portalPages.find((page) => page.path === path) || null;
}

export function portalArticles() {
  return portalPages.filter((page) => page.type === "article");
}
